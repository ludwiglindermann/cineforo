-- Borra las tablas si ya existen, para poder ejecutar el script de nuevo
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('USUARIO', 'ROL')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Tabla ROL: tipos de usuario con privilegios distintos
-- ---------------------------------------------------------------------
CREATE TABLE ROL (
    ID          NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE      VARCHAR2(30)  NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,
    CONSTRAINT PK_ROL PRIMARY KEY (ID),
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

-- ---------------------------------------------------------------------
-- Tabla USUARIO: cuentas del foro
-- PASSWORD guarda el hash BCrypt, nunca la clave en texto plano
-- ---------------------------------------------------------------------
CREATE TABLE USUARIO (
    ID             NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_USUARIO VARCHAR2(50)  NOT NULL,
    EMAIL          VARCHAR2(120) NOT NULL,
    PASSWORD       VARCHAR2(100) NOT NULL,
    ROL_ID         NUMBER(19)    NOT NULL,
    FECHA_REGISTRO TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ACTIVO         NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UQ_USUARIO_NOMBRE UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ROL_ID) REFERENCES ROL (ID),
    CONSTRAINT CK_USUARIO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

