-- ---------------------------------------------------------------------
-- Verificacion
-- ---------------------------------------------------------------------
SELECT * FROM CATEGORIA ORDER BY ID;

SELECT c.NOMBRE AS CATEGORIA, COUNT(t.ID) AS TEMAS
FROM   CATEGORIA c
LEFT JOIN TEMA t ON t.CATEGORIA_ID = c.ID
GROUP  BY c.NOMBRE
ORDER  BY c.NOMBRE;

SELECT t.ID, t.TITULO, t.ESTADO, COUNT(co.ID) AS COMENTARIOS
FROM   TEMA t
LEFT JOIN COMENTARIO co ON co.TEMA_ID = t.ID
GROUP  BY t.ID, t.TITULO, t.ESTADO
ORDER  BY t.ID;
