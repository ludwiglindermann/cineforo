BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('COMENTARIO', 'TEMA', 'CATEGORIA')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- Tabla CATEGORIA
-- ---------------------------------------------------------------------
CREATE TABLE CATEGORIA (
    ID          NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE      VARCHAR2(60)  NOT NULL,
    DESCRIPCION VARCHAR2(250) NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

-- ---------------------------------------------------------------------
-- Tabla TEMA: publicaciones del foro
-- ---------------------------------------------------------------------
CREATE TABLE TEMA (
    ID             NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO         VARCHAR2(150)  NOT NULL,
    CONTENIDO      VARCHAR2(4000) NOT NULL,
    CATEGORIA_ID   NUMBER(19)     NOT NULL,
    USUARIO_ID     NUMBER(19)     NOT NULL,
    FECHA_CREACION TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO         VARCHAR2(20)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_TEMA PRIMARY KEY (ID),
    CONSTRAINT FK_TEMA_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIA (ID),
    CONSTRAINT CK_TEMA_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);

-- ---------------------------------------------------------------------
-- Tabla COMENTARIO: respuestas a un tema
-- Si se elimina un tema, se eliminan sus comentarios
-- ---------------------------------------------------------------------
CREATE TABLE COMENTARIO (
    ID             NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CONTENIDO      VARCHAR2(2000) NOT NULL,
    TEMA_ID        NUMBER(19)     NOT NULL,
    USUARIO_ID     NUMBER(19)     NOT NULL,
    FECHA_CREACION TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO         VARCHAR2(20)   DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_COMENTARIO PRIMARY KEY (ID),
    CONSTRAINT FK_COMENTARIO_TEMA FOREIGN KEY (TEMA_ID) REFERENCES TEMA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_COMENTARIO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BANEADO'))
);

-- Indices para las busquedas mas comunes
CREATE INDEX IX_TEMA_CATEGORIA ON TEMA (CATEGORIA_ID);
CREATE INDEX IX_COMENTARIO_TEMA ON COMENTARIO (TEMA_ID);

